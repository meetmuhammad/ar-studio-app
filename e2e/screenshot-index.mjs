/**
 * node e2e/screenshot-index.mjs  ->  docs/qa/screenshot-index.md
 * Lists every saved screenshot as: screen | role | viewport | browser | file. The PNGs live under
 * qa-artifacts/screenshots/<phase>/<browser>/<role>/<screen>__<viewport>.png (git-ignored, local only).
 */
import fs from 'node:fs'
import path from 'node:path'
const root = 'qa-artifacts/screenshots'
const rows = []
for (const phase of fs.existsSync(root) ? fs.readdirSync(root) : []) for (const browser of fs.readdirSync(path.join(root, phase))) for (const role of fs.readdirSync(path.join(root, phase, browser)))
  for (const f of fs.readdirSync(path.join(root, phase, browser, role)).filter((x) => x.endsWith('.png'))) {
    const [screen, vp] = f.replace('.png', '').split('__')
    rows.push({ phase, browser, role, screen, vp, file: path.join(root, phase, browser, role, f) })
  }
rows.sort((a, b) => [a.phase, a.screen, a.role, a.browser].join('|').localeCompare([b.phase, b.screen, b.role, b.browser].join('|')) || parseInt(a.vp.replace(/\D/g, '')) - parseInt(b.vp.replace(/\D/g, '')))
const count = (k) => Object.entries(rows.reduce((m, r) => ((m[r[k]] = (m[r[k]] ?? 0) + 1), m), {})).map(([a, b]) => `${a} ${b}`).join(', ')
let out = `# Screenshot index\n\nGenerated by \`node e2e/screenshot-index.mjs\`. ${rows.length} screenshots. The PNGs are in \`qa-artifacts/\` on the machine that ran the tests\n(git-ignored: they contain the local synthetic data, and are regenerated by \`npx playwright test\`).\n\nBy phase: ${count('phase')}. By browser: ${count('browser')}. By role: ${count('role')}.\n\n`
out += `- **before** = the app before this work (baseline sweep, Chromium only). **after** = final.\n- Screens named \`dialog-*\` are modal dialogs opened with seeded data. The browser is a rendering engine (Chromium or WebKit) at the stated viewport; none is a physical device.\n\n`
out += '| Phase | Screen | Role | Viewport | Browser | File |\n|---|---|---|---|---|---|\n'
for (const r of rows) out += `| ${r.phase} | ${r.screen} | ${r.role} | ${r.vp} | ${r.browser} | \`${r.file}\` |\n`
fs.mkdirSync('docs/qa', { recursive: true }); fs.writeFileSync('docs/qa/screenshot-index.md', out)
console.log('wrote docs/qa/screenshot-index.md', rows.length, 'rows')
